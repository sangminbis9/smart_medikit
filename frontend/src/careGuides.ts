// 검색은 가이드 탐색에만 사용하며 제품 효능 매칭에는 사용하지 않는다.
export function findCareGuides(query: string, category = ''): CareGuide[] {
  const terms = query.trim().toLocaleLowerCase('ko-KR').split(/\s+/);
  // 선택 카테고리와 모든 검색어를 동시에 적용한다.
  return careGuides.filter(function matches(item) {
    const text =
      `${item.name} ${item.category} ${item.description}`.toLocaleLowerCase(
        'ko-KR',
      );
    // 단어가 여러 개면 모두 포함된 증상만 표시한다.
    return (
      (!category || item.category === category) &&
      terms.every(function includes(term) {
        return text.includes(term);
      })
    );
  });
}
