export type MedicineCategory = keyof typeof medicineCategories;
export type CareStep = {
  title: string;
  description: string;
  medicineCategories: MedicineCategory[];
};
export type CareGuide = {
  id: string;
  category: (typeof careCategories)[number];
  name: string;
  description: string;
  notice: string;
  steps: CareStep[];
  relatedMedicineCategories: MedicineCategory[];
  warningSigns: string[];
  urgentNotice: string | null;
  sources: { title: string; url: string }[];
  version: string;
  sourceCheckedAt: string;
};

// 공통 메타데이터를 붙이고 단계에 실제 연결된 약품 유형만 모은다.
function guide(
  id: string,
  category: CareGuide['category'],
  name: string,
  description: string,
  steps: [string, string, MedicineCategory[]?][],
  warningSigns: string[],
  sources: [string, string][],
  urgentNotice: string | null = null,
): CareGuide {
  const related = new Set<MedicineCategory>();
  // 비약물 단계는 빈 유형 목록으로 보존한다.
  const content = steps.map(function step([
    title,
    description,
    categories = [],
  ]) {
    for (const category of categories) related.add(category);
    return { title, description, medicineCategories: categories };
  });
  return {
    id,
    category,
    name,
    description,
    notice: careNotice,
    steps: content,
    relatedMedicineCategories: [...related],
    warningSigns,
    urgentNotice,
    // 출처는 증상별 원문 링크로 연결한다.
    sources: sources.map(function source([title, path]) {
      return { title: `NHS · ${title}`, url: `https://www.nhs.uk/${path}/` };
    }),
    version: '2026-11-02.1',
    sourceCheckedAt: '2026-11-02',
  };
}

